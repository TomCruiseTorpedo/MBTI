#!/usr/bin/env python3
"""Build the compatibility chart from a few author-made rules.

The rules live here and nowhere else. Running this script rewrites
compatibility/chart.md and compatibility/chart.json, so edit the rules
below rather than the generated files.

These rules are for fun. They echo the "best match" pairs that circulate
in Korean blog compatibility charts (ENFP-INFJ as 천생연분 and so on).
Another family of Korean charts follows socionics, which calls complete
opposites the ideal pair; those land in Extra effort here. None of this
is research.
"""

import json
from itertools import combinations_with_replacement
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "compatibility"

TYPES = [
    "INTJ", "INTP", "ENTJ", "ENTP",
    "INFJ", "INFP", "ENFJ", "ENFP",
    "ISTJ", "ISFJ", "ESTJ", "ESFJ",
    "ISTP", "ISFP", "ESTP", "ESFP",
]

# Order matters: the first rule that matches wins.
TIERS = {
    "twins": {
        "label": "Twins",
        "emoji": "👯",
        "hearts": 4,
        "blurb": "Instant understanding. You'll also share the same blind spots.",
    },
    "perfect": {
        "label": "Perfect pair (찰떡)",
        "emoji": "💞",
        "hearts": 5,
        "blurb": "You see the world the same way and fill each other's gaps.",
    },
    "easy": {
        "label": "Easy chemistry",
        "emoji": "😊",
        "hearts": 4,
        "blurb": "Same wavelength on what's worth talking about.",
    },
    "spark": {
        "label": "Spark",
        "emoji": "⚡",
        "hearts": 3,
        "blurb": "Different worlds, shared values. Expect great debates.",
    },
    "extra-effort": {
        "label": "Extra effort",
        "emoji": "🧗",
        "hearts": 2,
        "blurb": "Different on both what you notice and how you decide. Worth it if you're curious.",
    },
}

# One line per letter axis, for the agent to build a "why" from.
LETTER_LINES = {
    "EI": {
        "E": "You both think out loud.",
        "I": "You both like time to think first.",
        "diff": "One brings the energy, the other the focus.",
    },
    "SN": {
        "S": "You both like facts and specifics.",
        "N": "You both love big ideas and what-ifs.",
        "diff": "One sees the details, the other the big picture.",
    },
    "TF": {
        "T": "You both go straight to fixing the problem.",
        "F": "You both care how everyone feels.",
        "diff": "One fixes, one feels. Cue the \"are you a T?\" moment.",
    },
    "JP": {
        "J": "You both like a plan.",
        "P": "You both like to wing it.",
        "diff": "One plans, one improvises.",
    },
}
AXES = list(LETTER_LINES)  # index i of a type code is axis AXES[i]


def tier(a: str, b: str) -> str:
    same = [x == y for x, y in zip(a, b)]
    ei, sn, tf, jp = same
    if a == b:
        return "twins"
    if sn and not ei and not jp:
        return "perfect"
    if sn:
        return "easy"
    if tf:
        return "spark"
    return "extra-effort"


def why(a: str, b: str) -> list[str]:
    lines = []
    for axis, x, y in zip(AXES, a, b):
        lines.append(LETTER_LINES[axis][x] if x == y else LETTER_LINES[axis]["diff"])
    return lines


def build() -> dict:
    matrix = {a: {b: tier(a, b) for b in TYPES} for a in TYPES}
    by_type = {
        a: {t: [b for b in TYPES if matrix[a][b] == t] for t in TIERS}
        for a in TYPES
    }
    return {"tiers": TIERS, "letter_lines": LETTER_LINES, "matrix": matrix, "by_type": by_type}


def check(data: dict) -> None:
    matrix = data["matrix"]
    for a in TYPES:
        for b in TYPES:
            assert matrix[a][b] == matrix[b][a], f"not symmetric: {a} {b}"
    expected = {"twins": 1, "perfect": 2, "easy": 5, "spark": 4, "extra-effort": 4}
    for a, tiers in data["by_type"].items():
        counts = {t: len(v) for t, v in tiers.items()}
        assert counts == expected, f"{a}: {counts}"
    pairs = list(combinations_with_replacement(TYPES, 2))
    assert len(pairs) == 136, len(pairs)


def render_md(data: dict) -> str:
    tiers, matrix, by_type = data["tiers"], data["matrix"], data["by_type"]
    out = [
        "# Compatibility chart",
        "",
        "> Generated by `scripts/build_compatibility.py`. Edit the rules there, then re-run it; don't edit this file by hand.",
        "",
        "**For fun, author-made rules.** Like the 궁합 (compatibility) charts that circulate in Korea, this chart has no scientific basis. "
        "Its \"perfect pair\" rule echoes the 천생연분 (soulmate) pairs most often shared in Korean blog charts, such as ENFP–INFJ. "
        "Another family of Korean charts follows socionics, which calls complete opposites (such as ENTP–ISFJ) the ideal pair; "
        "in this chart those are Extra effort. The charts disagree, which is part of the fun. "
        "Types are never a reason to judge, hire or reject anyone.",
        "",
        "## The rules",
        "",
        "Compare two four-letter codes. The first rule that fits wins:",
        "",
        "1. Same code: **Twins**.",
        "2. Same S/N letter, but opposite E/I and opposite J/P: **Perfect pair (찰떡)**.",
        "3. Same S/N letter: **Easy chemistry**.",
        "4. Different S/N letter, same T/F letter: **Spark**.",
        "5. Everything else: **Extra effort**.",
        "",
        "| | Tier | Hearts | What it means |",
        "|---|---|---|---|",
    ]
    for t in tiers.values():
        out.append(f"| {t['emoji']} | {t['label']} | {'♥' * t['hearts']} | {t['blurb']} |")

    out += [
        "",
        "## How an agent uses it",
        "",
        "- **Best-match persona:** one of the person's two perfect-pair types. Pick between them using the style the person preferred in the taste test.",
        "- **Wildcard:** a Spark type, for someone who wants to be challenged, or their Twin, for someone who wants to feel understood.",
        "- **Explaining the chemistry:** combine the four letter lines below into two or three sentences, then add the tier's one-liner.",
        "- Never present Extra effort as bad. It just takes more translating, and some charts (socionics) say total opposites are the ideal match.",
        "",
        "## Best matches by type",
        "",
        "| Type | 💞 Perfect pair | 👯 Twin | ⚡ Spark |",
        "|---|---|---|---|",
    ]
    for a in TYPES:
        t = by_type[a]
        out.append(f"| {a} | {', '.join(t['perfect'])} | {a} | {', '.join(t['spark'])} |")

    out += [
        "",
        "## Full chart",
        "",
        "| | " + " | ".join(TYPES) + " |",
        "|---" * (len(TYPES) + 1) + "|",
    ]
    for a in TYPES:
        out.append(f"| **{a}** | " + " | ".join(tiers[matrix[a][b]]["emoji"] for b in TYPES) + " |")

    out += [
        "",
        "## Letter chemistry",
        "",
        "One line per letter, depending on whether the two codes share it.",
        "",
        "| Letters | Same | Different |",
        "|---|---|---|",
    ]
    for axis, lines in data["letter_lines"].items():
        same = " / ".join(f"{k}: {v}" for k, v in lines.items() if k != "diff")
        out.append(f"| {axis[0]}/{axis[1]} | {same} | {lines['diff']} |")

    example_a, example_b = "ENFP", "INFJ"
    out += [
        "",
        f"**Example, {example_a} + {example_b}:** " + " ".join(why(example_a, example_b))
        + f" {tiers[matrix[example_a][example_b]]['blurb']}",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    data = build()
    check(data)
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "chart.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (OUT_DIR / "chart.md").write_text(render_md(data), encoding="utf-8")
    print(f"wrote {OUT_DIR / 'chart.md'} and {OUT_DIR / 'chart.json'}")


if __name__ == "__main__":
    main()
